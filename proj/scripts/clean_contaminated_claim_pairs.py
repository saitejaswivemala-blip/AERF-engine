#!/usr/bin/env python3
"""
scripts/clean_contaminated_claim_pairs.py

Removes claim_pairs rows with matching_method='curated_real_model_evaluation'
from a database that is supposed to hold ONLY genuine, corpus-wide
Phase3Pipeline.run() output (see matching/claim_matcher.py, whose
MatchDecision.method is always the literal string
'embedding→entity-alignment→bidirectional-NLI' -- never
'curated_real_model_evaluation').

Why these rows exist: scripts/evaluate_curated_mapping_before_isolation.py
(now retired) wrote its curated-evaluation results directly into whatever
--db path was given, before the per-configuration database isolation
mechanism existed. Run against experiments/runs/experiment.db, this
polluted the SHARED "real pipeline" database with 4 rows that don't
represent genuine cross-document corpus reasoning -- see
experiments/reports/ for the fuller writeup of this bug and its fix in
scripts/evaluate_curated_mapping.py (validated_as was also being written
as None for these rows, independent of the isolation issue).

This script only ever deletes rows carrying that exact matching_method
fingerprint (via Repository.delete_claim_pairs_by_matching_method(), which
is a plain, exact-match DELETE -- see its docstring) -- it cannot remove
any row produced by the real pipeline. It does not touch papers, chunks,
claims, entities, embeddings, aerf_scores, or any other table.

The 7 experiments/runs/eval_dbs/*.db files (plus baseline_seed.db) are not
individually repaired by this script: they are wholly regenerated by
scripts/evaluate_curated_mapping.py's own shutil.copy2 seeding on every
run (fresh copy of experiments/runs/experiment.db -> baseline_seed.db ->
each config's isolated .db), so once experiment.db is clean and the
validated_as fix is in place, the next real run produces clean eval_dbs
automatically. This script instead deletes the current, stale eval_dbs
files outright (they are disposable, run-regenerated artifacts by design,
never the source of truth) so nothing stale is left around to be
mistakenly inspected as if current.

Usage:
    python scripts/clean_contaminated_claim_pairs.py
    python scripts/clean_contaminated_claim_pairs.py --dry-run
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from db.repository import Repository  # noqa: E402

MATCHING_METHOD = "curated_real_model_evaluation"
EXPERIMENT_DB = Path("experiments/runs/experiment.db")
EVAL_DB_DIR = Path("experiments/runs/eval_dbs")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--db", default=str(EXPERIMENT_DB))
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--keep-eval-dbs", action="store_true",
                         help="Don't delete the stale experiments/runs/eval_dbs/*.db files.")
    args = parser.parse_args()

    db_path = Path(args.db)
    if not db_path.exists():
        raise FileNotFoundError(f"{db_path} does not exist.")

    repo = Repository(db_path)
    import sqlite3
    con = sqlite3.connect(db_path)
    con.row_factory = sqlite3.Row
    rows = con.execute(
        "SELECT claim_a_id, claim_b_id, nli_label, nli_confidence, validated_as "
        "FROM claim_pairs WHERE matching_method = ?", (MATCHING_METHOD,)
    ).fetchall()
    con.close()

    print(f"Found {len(rows)} row(s) in {db_path} with matching_method={MATCHING_METHOD!r}:")
    for r in rows:
        print(f"  claim_a_id={r['claim_a_id']} claim_b_id={r['claim_b_id']} "
              f"nli_label={r['nli_label']} nli_confidence={r['nli_confidence']} "
              f"validated_as={r['validated_as']}")

    if args.dry_run:
        print("\n--dry-run: nothing deleted.")
        return 0

    deleted = repo.delete_claim_pairs_by_matching_method(MATCHING_METHOD)
    print(f"\nDeleted {deleted} row(s) from {db_path}.")

    if not args.keep_eval_dbs and EVAL_DB_DIR.exists():
        removed = []
        for f in sorted(EVAL_DB_DIR.glob("*.db")):
            f.unlink()
            removed.append(f.name)
        if removed:
            print(f"Removed {len(removed)} stale eval_dbs file(s) (regenerated fresh on next real "
                  f"curated-evaluation run): {removed}")

    return deleted


if __name__ == "__main__":
    main()
